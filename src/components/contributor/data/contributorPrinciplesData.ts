// Helper to look up any field by ID
export const findFieldById = (fieldId: string): FieldDefinition | undefined => {
  for (const p of PRINCIPLES_CONFIG) {
    for (const sub of p.subsections) {
      const found = sub.fields.find(f => f.id === fieldId);
      if (found) return found;
    }
  }
  return undefined;
};
